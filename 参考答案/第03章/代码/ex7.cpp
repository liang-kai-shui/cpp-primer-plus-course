// 题目要求：
//   1. 让用户按欧洲风格输入耗油量（每 100 公里消耗多少升）；
//   2. 转换成美国风格（每加仑跑多少英里）。
// 关键点（题目原话）：
//   美国方法（距离/燃料）与欧洲方法（燃料/距离）方向相反；
//   100 公里 = 62.14 英里。
//   ⚠️ 教材 p87 印的是"1 加仑 = 3.875 升"，这个数字和教材自己给的例子对不上。
//      用 3.875 反推：62.14 × 3.875 = 240.79，19 mpg 会算成 12.67、
//      27 mpg 会算成 8.92，都不符教材说的"12.4 / 8.7"。
//      用美国加仑真值 3.785：62.14 × 3.785 = 235.2，19 → 12.38、27 → 8.71，
//      正好对上教材的例子。**所以是 3.875 印错了，应为 3.785。**
//      本程序第 4 行用的是正确的 3.785。
//   推导：
//     设欧洲油耗 E 升/100km，则 100 公里 = 62.14 英里，E 升 = E / 3.785 加仑，
//     每加仑跑的英里数 mpg = 62.14 / (E / 3.785) = 62.14 * 3.785 / E = 235.2 / E。
//   本程序第 12 行用同一套换算因子把常数项合并成了"先乘后除"：
//     mpg = (MILES_PER_100KM * LITERS_PER_GALLON) / liters_per_100km;
// 预期输出（用教材给的两组数验证）：
//   输入 19 → 12.3789 mpg（教材说约 12.4 ✅）
//   输入 27 → 8.71111 mpg（教材说约 8.7  ✅）
// 编译：g++ -std=c++17 -Wall -Wextra ex7.cpp -o ex7
// ============================================================

#include <iostream>

const double MILES_PER_100KM = 62.14;
const double LITERS_PER_GALLON = 3.785;

int main()
{
    using namespace std;
    double liters_per_100km;
    cout << "请输入欧洲风格的耗油量（升/100公里）：";
    cin >> liters_per_100km;
    double mpg = (MILES_PER_100KM * LITERS_PER_GALLON) / liters_per_100km;
    cout << "美国风格的耗油量为：" << mpg << " mpg" << endl;

    return 0;
}
