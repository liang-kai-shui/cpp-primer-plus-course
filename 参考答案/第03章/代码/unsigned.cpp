// 说明：这个文件不是教材的编程练习，而是任务 2 的"实验 D：unsigned 的陷阱"
//       留下的代码。放在这里是为了让"实验 D 的实测输出"可以复现。
// 实验目的：
//   先猜 if (u - v > 0) 会不会成立，再运行验证。
// 关键点：无符号整数没有负数。
//   unsigned int 是 32 位，取值范围 0 ~ 4294967295（2³² - 1）。
//   5u - 10u 的结果按 2³² 取模：5 - 10 = -5，-5 + 4294967296 = 4294967291。
//   也就是"从 0 再往下走就绕回最大值"：5 - 5 = 0，减 1 绕到 4294967295，
//   再减 4 得 4294967291。
//   而 u - v 的类型是 unsigned int，**无符号数永远 ≥ 0**，
//   所以 u - v > 0 恒为真——这个分支一定会进去。
// 预期输出：
//   5u - 10u = 4294967291
//   居然进来了！
// 实践意义：无符号数参与减法、循环边界判断时极易写出"永远为真/永远为假"的条件，
//   而且编译器不会报错，只给出莫名其妙的结果。
// 编译：g++ -std=c++17 -Wall -Wextra unsigned.cpp -o unsigned
// ============================================================

#include <iostream>
int main()
{
    unsigned int u = 5;
    unsigned int v = 10;
    std::cout << "5u - 10u = " << u - v << std::endl;
    if (u - v > 0)
        std::cout << "居然进来了！" << std::endl;
    return 0;
}
