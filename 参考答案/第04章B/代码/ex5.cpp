// 【这题在练什么】
//   1. 写一个结构声明（struct CandyBar），三个成员类型各不相同：
//        string  brand     —— 品牌（可能有空格，比如 "Mocha Munch"）
//        double  weight    —— 重量（有小数）
//        int     calories  —— 卡路里（整数）
//   2. 体会「结构声明」和「结构变量」是两件事：
//        上面那段 struct CandyBar { ... };  只是画了一张表格模板，不占内存；
//        main 里的 CandyBar snack;          才是按模板填出来的一行数据。
//   3. 按题目要求，在【声明 snack 的同时】用 {..} 初始化 —— 不能先声明再逐个赋值。
//   4. 显示这个结构的内容。
//
// 【预期输入】无（程序不需要输入）
//
// 【预期输出】
//   ===== 糖块信息 =====
//   品牌    : Mocha Munch
//   重量    : 2.3 盎司
//   卡路里  : 350
//
// 【实测输出】（g++ 8.1.0 / MinGW-w64 实跑结果，原样抄录）
//   ===== 糖块信息 =====
//   品牌    : Mocha Munch
//   重量    : 2.3 盎司
//   卡路里  : 350
//
//   （结构类型 CandyBar 的一行数据占 48 字节）
//
//   说明：最后一行不是题目要求的输出，只是顺手用 sizeof 演示一下
//   「结构声明不占内存、结构变量才占内存」—— 48 字节里有一部分是
//   编译器为了对齐插入的空隙（string 8 + double 8 + int 4 = 20，
//   对齐后是 48）。
//
// 【编译】g++ -std=c++17 -Wall -Wextra ex5.cpp -o ex5   （0 错误 0 警告）
// ============================================================

#include <iostream>
#include <string>

// ---------- 第一步：结构声明（只是模板，不分配内存）----------
struct CandyBar
{
    std::string brand;     // 品牌：用 std::string，因为 "Mocha Munch" 中间有空格
    double      weight;    // 重量：可以有小数
    int         calories;  // 卡路里：整数
};                         // ⚠️ 这个分号千万别忘

int main()
{
    using namespace std;

    // ---------- 第二步：声明变量时直接初始化 ----------
    // 顺序必须和结构声明里一致：brand, weight, calories
    CandyBar snack = {"Mocha Munch", 2.3, 350};

    // ---------- 第三步：显示内容 ----------
    cout << "===== 糖块信息 =====\n";
    cout << "品牌    : " << snack.brand    << "\n";
    cout << "重量    : " << snack.weight   << " 盎司\n";
    cout << "卡路里  : " << snack.calories << "\n";

    // ---------- 顺便验证一下「声明不占内存、变量才占内存」----------
    // sizeof(CandyBar) 是「一行数据有多大」，和具体的 snack 是两回事。
    cout << "\n（结构类型 CandyBar 的一行数据占 " << sizeof(CandyBar) << " 字节）\n";

    return 0;
}
