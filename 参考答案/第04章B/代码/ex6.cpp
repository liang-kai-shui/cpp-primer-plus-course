// 【这题在练什么】
//   1. 「结构数组」：把编程练习 5 的 CandyBar 拿来，做一个含 3 个元素的数组。
//      数组 = 同类型的多个数据排一排；结构 = 不同类型的数据打成一包；
//      结构数组 = 每个元素都是一个结构 —— 天然的「表格」。
//   2. 两层大括号的初始化写法：外面一层是数组，里面每层是一个结构。
//   3. 用 for 循环遍历，访问方式是「先下标，后点」：bars[i].brand
//      （先取出第 i 个结构，再取它的 brand 成员）
//
// 【预期输入】无（程序不需要输入）
//
// 【预期输出】
//   ===== 糖块清单（3 种）=====
//   序号  品牌                 重量      卡路里
//   --------------------------------------------------
//   1     Mocha Munch          2.3       350
//   2     Butterfinger         1.8       280
//   3     Crunchy Caramel      3.5       420
//   --------------------------------------------------
//   合计             7.6      1050
//
// 【实测输出】（g++ 8.1.0 / MinGW-w64 实跑结果，原样抄录；
//   品牌和重量之间用的是制表符 \t，所以在某些编辑器里列不会完全对齐，这是正常的）
//   ===== 糖块清单（3 种）=====
//   序号  品牌                 重量      卡路里
//   --------------------------------------------------
//   1     Mocha Munch	2.3	350
//   2     Butterfinger	1.8	280
//   3     Crunchy Caramel	3.5	420
//   --------------------------------------------------
//   合计             7.6      1050
//
// 【编译】g++ -std=c++17 -Wall -Wextra ex6.cpp -o ex6   （0 错误 0 警告）
// ============================================================

#include <iostream>
#include <string>

struct CandyBar
{
    std::string brand;
    double      weight;
    int         calories;
};

int main()
{
    using namespace std;

    // ---------- 结构数组：外层 {} 是数组，内层 {} 是每个元素（结构）----------
    CandyBar bars[3] = {
        {"Mocha Munch",     2.3, 350},
        {"Butterfinger",    1.8, 280},
        {"Crunchy Caramel", 3.5, 420},
    };

    cout << "===== 糖块清单（3 种）=====\n";
    cout << "序号  品牌                 重量      卡路里\n";
    cout << "--------------------------------------------------\n";

    // ---------- 遍历：先下标 bars[i]，再点 .brand ----------
    for (int i = 0; i < 3; ++i)
    {
        cout << i + 1 << "     "
             << bars[i].brand << "\t"
             << bars[i].weight << "\t"
             << bars[i].calories << "\n";
    }

    // ---------- 顺便：算总重量和总卡路里（结构数组最常见的用法）----------
    double totalWeight   = 0;
    int    totalCalories = 0;
    for (int i = 0; i < 3; ++i)
    {
        totalWeight   += bars[i].weight;
        totalCalories += bars[i].calories;
    }
    cout << "--------------------------------------------------\n";
    cout << "合计             " << totalWeight << "      " << totalCalories << "\n";

    return 0;
}
