// 题目：编程练习 2（教材 p53–54）——把以 long 为单位的距离换算成码（1 long = 220 码）
// ------------------------------------------------------------
// 思路要点：
//   1. 先提示，再用 cin 读入一个距离；
//   2. 直接输出「距离 × 220」。
// 值得注意：
//   教材要求用 long 类型，这里用的是 int——小数值结果一样，
//   但输入很大时 int × 220 会溢出，写 long 更贴合题意。
//   输出末尾没有换行，程序结束时结果会紧贴命令行提示符。
// ============================================================

#include <iostream>

int main()
{
    std::cout << "Enter a distance in long:";
    int distance;
    std::cin >> distance;
    std::cout << distance * 220;
    return 0;
}