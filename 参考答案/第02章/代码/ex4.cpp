// 题目：编程练习 4（教材 p53–54）——输入年龄，显示该年龄包含多少个月
// ------------------------------------------------------------
// 思路要点：
//   1. 用 cin 读入年龄，输出「年龄 × 12」（1 年 = 12 个月）；
//   2. 输出格式自己设计，这里写成 "29 years = 348 months"。
// 值得注意：
//   本题不要求用户定义的函数，所以全部写在 main() 里；
//   变量名用的是 year（其实表示“年龄”），叫 age 更贴切。
// ============================================================

#include <iostream>

int main()
{
    using namespace std;
    int year;
    cout << "Enter your age: ";
    cin >> year;
    cout << year << " years = " << year * 12 << " months" << endl;
    return 0;
}