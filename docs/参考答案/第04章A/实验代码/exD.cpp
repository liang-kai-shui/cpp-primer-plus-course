// ============================================================
//  实验 D：混合输入陷阱的一种修法（用解法 2）
// ------------------------------------------------------------
//  这个实验在验证什么：
//  在读数字之后、读下一项之前，把 cin >> 残留的换行符清掉，问题就消失。
//  这里用的是"解法 2"——把两步连起来写：
//      (cin >> year).get();
//  意思是：先读 year，然后对同一个 cin 对象再调一次 get() 把换行符取走。
//
//  实测结论（输入 2026 / 42）：
//      Enter the year: Enter the address:    ->2026 / 42
//  两次输入的等待都正常出现，没有再"跳过"输入。
//
//  ⚠️ 两个说明：
//  1. 本实验的 address 变量是 int（变量名拼作 adress），
//     所以这里必须输入数字；输入文字会让 cin >> 失败、变量留成不确定的值。
//     主实验 06_mixed_input_trap.cpp 里那个 address 是 char 数组，才是完整对照。
//  2. 清换行符这件事只在"下一个操作要读整行（getline / get）"时才有必要。
//     如果下一个操作是 cin >>，它会自动跳过空白，看不出任何问题。
// ============================================================
#include <iostream>

int main()
{
    using namespace std;
    int year, adress;
    cout << "Enter the year: ";
    (cin >> year).get();
    cout << "Enter the address: ";
    cin >> adress;
    cout << "   ->" << year << " / " << adress;
}