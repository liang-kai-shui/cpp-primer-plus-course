// ============================================================
//  实验 C：数组能不能整体赋值（★ 这个文件是故意编译不过的）
// ------------------------------------------------------------
//  这个实验在验证什么：
//  数组整体赋值 b = a; 是【编译期错误】，因为 C++ 里数组不是"一个值"。
//  a 这个名字在参与表达式时会"退化"成第一个元素的地址，
//  而"给一排柜子赋值"在语法上不成立，所以编译器直接拒绝。
//
//  实测报错原文（g++ 8.1.0 / MinGW-w64，-std=c++17 -Wall -Wextra）：
//      error: invalid array assignment
//           b = a;
//               ^
//
//  ⚠️ 本文件编译【必然失败】，这是实验的一部分，不是代码写错了。
//     不要试图"修好"它。要复制数组内容，只能逐个元素复制：
//         for (int i = 0; i < 3; ++i) b[i] = a[i];
// ============================================================
#include <iostream>

int main()
{
    using namespace std;
    int a[3] = {1, 2, 3};
    int b[3];
    b = a;
}