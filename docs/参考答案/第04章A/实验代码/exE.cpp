// ============================================================
//  实验 E：C 风格字符串用 == 比较会得到什么
// ------------------------------------------------------------
//  这个实验在验证什么：
//  数组名参与比较时代表的是"地址"，不是内容。
//  所以两个内容完全相同的数组用 == 比较，结果也是 false。
//  要比内容必须用 <cstring> 里的 strcmp。
//
//  实测结论（直接运行，不需要输入）：
//      (a == b)           -> 0    （false：比的是两个数组的地址，地址不同）
//      (strcmp(a,b) == 0) -> 1    （true：strcmp 比的是内容）
//
//  ⚠️ 一个容易写反的地方：strcmp 用 0 表示"相等"，
//     而 0 在 if 里是"假"，所以一定要把 == 0 写上，
//     写成 if (strcmp(a, b)) 意思正好相反。
// ============================================================
#include <iostream>
#include <cstring>

int main()
{
    char a[] = "apple";
    char b[] = "apple";
    std::cout << (a == b) << std::endl;
    std::cout << (strcmp(a, b) == 0) << std::endl;
    return 0;
}