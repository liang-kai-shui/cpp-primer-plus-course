// 编程练习 7 · 参考答案（教材 p124）
// ------------------------------------------------------------
// 【这题在练什么】
//   把上一课（数组与字符串）和本课（结构）合起来用：
//   1. 设计一个结构 Pizza，装三样信息：
//        string company    —— 公司名称，【可以有多个单词】（如 "Pizza Hut"）
//        double diameter   —— 直径（有小数）
//        double weight     —— 重量（有小数）
//   2. 请用户输入这三项，再原样显示出来。
//
//   ⚠️⚠️ 本题的经典陷阱：换行符残留 ⚠️⚠️
//   ------------------------------------------------------------
//   题目的输入顺序是【先直径（数字）→ 再公司名（整行）】。
//   如果你这样写：
//       cin >> diameter;          // 用 >> 读数字
//       getline(cin, company);    // 紧接着用 getline 读整行
//   那么 company 会读到【一个空字符串】——公司名被吞掉了！
//
//   为什么？因为 cin >> 读数字时，只把 "12.5" 这几个字符取走，
//   你在键盘上敲的那个【回车（换行符 '\n'）】还留在输入缓冲区里。
//   而 getline 的规则是「读到换行符为止」，它一上来就撞见那个残留的换行符，
//   于是认为「这一行是空的」，把空字符串交给了 company。
//
//   本程序采用的正确做法（三种任选其一）：
//       ① 读完数字后手动吃掉那个换行符：   cin.get();
//       ② 把「读数字」和「吃掉换行符」写在一起：(cin >> diameter).get();
//       ③ 全部用 getline 读，再自己把字符串转成数字（本题不需要，略）
//   本程序用 ②，因为它把「读走数字」和「吃掉换行符」写在同一个表达式里，
//   意图最清楚，也不容易忘记。
//   ------------------------------------------------------------
//
// 【预期输入】顺序按程序的提问来（题目要求【先读直径】，再读公司名，再读重量）
//   第一行：12.5          ← 直径（数字）
//   第二行：Pizza Hut     ← 公司名（含空格的一整行）
//   第三行：3.2           ← 重量（数字）
//
// 【预期输出】
//   ===== 比萨饼分析报告 =====
//   公司名称 : Pizza Hut
//   直径     : 12.5 英寸
//   重量     : 3.2 磅
//
// 【实测输出】（g++ 8.1.0 / MinGW-w64 实跑结果，原样抄录）
//   请输入披萨饼的直径（英寸，可以有小数）：请输入披萨饼公司的名称（可以包含多个单词）：请输入披萨饼的重量（磅，可以有小数）：
//   ===== 比萨饼分析报告 =====
//   公司名称 : Pizza Hut
//   直径     : 12.5 英寸
//   重量     : 3.2 磅
//
//   （三句提问连在一行，是因为实测时用管道一次把三行输入喂给了程序，
//     屏幕上的回显被吃掉了；在键盘上手工输入时会正常分行。）
//
// 【实测：如果不加 (cin >> ...).get()，陷阱长什么样】
//   把上面那行改成 cin >> p.diameter; 再单独写 getline(cin, p.company);
//   同样喂入 12.5 / Pizza Hut / 3.2，结果公司名读到了一个空字符串：
//
//     [公司名读到了什么] -> []
//     公司名的长度 = 0
//
//   公司名就被那个残留的换行符吞掉了 —— 这就是本题最值得记住的坑。
//
// 【编译】g++ -std=c++17 -Wall -Wextra ex7.cpp -o ex7   （0 错误 0 警告）
// ============================================================

#include <iostream>
#include <string>

struct Pizza
{
    std::string company;    // 公司名称：可能有多个单词，所以用 string 配 getline
    double      diameter;   // 直径（英寸）
    double      weight;     // 重量（磅）
};
// 💡 注意：这里三个成员的【书写顺序】和程序【提问的顺序】不一样，
//    这完全没问题 —— 因为上面这个顺序只在「用大括号 {..} 初始化」时才有意义；
//    本程序是一个成员一个成员单独赋值的，所以先后随便，看名字就对上了。
//    （「大括号初始化要按顺序」这条规矩，见讲义 4.3 节。）

int main()
{
    using namespace std;

    Pizza p;

    // ---------- 按题目要求：先问直径（数字）----------
    cout << "请输入披萨饼的直径（英寸，可以有小数）：";
    // ⚠️ 关键：题目要求先读数字，所以这里必须处理「换行符残留」。
    //    (cin >> p.diameter) 的结果是 cin 本身，紧接着 .get() 吃掉那个残留的换行符。
    (cin >> p.diameter).get();

    // ---------- 再问公司名（整行，可能含空格）----------
    cout << "请输入披萨饼公司的名称（可以包含多个单词）：";
    getline(cin, p.company);      // 读一整行，空格也一起读进来

    // ---------- 最后问重量（数字）----------
    cout << "请输入披萨饼的重量（磅，可以有小数）：";
    cin >> p.weight;

    // ---------- 显示 ----------
    cout << "\n===== 比萨饼分析报告 =====\n";
    cout << "公司名称 : " << p.company  << "\n";
    cout << "直径     : " << p.diameter << " 英寸\n";
    cout << "重量     : " << p.weight   << " 磅\n";

    return 0;
}
