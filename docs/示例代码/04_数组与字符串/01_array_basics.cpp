// ============================================================
//  L04 · 示例 1：数组是什么，怎么用            （教材 4.1, p87-90）
// ------------------------------------------------------------
//  【先想一个问题】如果要存 100 个学生的成绩，你会怎么做？
//     int s1, s2, s3, ... s100;      <- 不可能这么写
//   数组就是来解决这个问题的：
//     一组【同类型】的、【连续】存放的变量，用【下标】访问。
// ============================================================
#include <iostream>

int main()
{
    using namespace std;

    // ---------- 声明：类型 名字[元素个数]; ----------
    int scores[5]; // 5 个 int，在内存里紧挨着排

    // ---------- 赋值：用下标 ----------
    scores[0] = 90; // 第一个元素的下标是 0，不是 1！
    scores[1] = 85;
    scores[2] = 78;
    scores[3] = 92;
    scores[4] = 88; // 最后一个元素的下标是 4 = 5-1

    // ---------- 遍历：数组和 for 循环是天生一对 ----------
    cout << "5 个成绩：";
    for (int i = 0; i < 5; ++i)     // 注意是 i < 5，不是 i <= 5
    {
        cout << scores[i] << " ";
    }
    cout << endl;

    // ---------- sizeof：数组占多少字节 ----------
    cout << "\nsizeof(scores)      = " << sizeof(scores) << " 字节\n";
    cout << "sizeof(scores[0])   = " << sizeof(scores[0]) << " 字节\n";
    cout << "所以元素个数 = " << sizeof(scores) / sizeof(scores[0]) << "\n";
    cout << "  ^ 这是 C++ 里「求数组长度」的经典写法（后面会讲更安全的办法）\n";

    // ---------- 内存地址：证明它们是连续存放的 ----------
    cout << "\n各元素的内存地址（注意每个差 4 字节 = sizeof(int)）：\n";
    for (int i = 0; i < 5; ++i)
    {
        cout << "  scores[" << i << "] 的地址 = " << &scores[i] << "\n";
    }
    cout << "  ^ 连续！这就是「数组」这个名字的由来\n";

    return 0;
}