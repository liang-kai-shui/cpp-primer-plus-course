// ============================================================
//  示例 1：凯撒密码（修复 + 函数化）
// ------------------------------------------------------------
//  这个示例以 一份练习用的凯撒密码代码 为原型。
//  （说明：这份代码保留了原样，用来练习「读别人的代码找 bug」。）
//  它有两个问题，本示例逐个处理：
//
//  【问题 1 · 真 bug】字母越界
//      原代码写的是：  s[i] = 'A' + (s[i] - 'A' + 3)
//      输入 XYZ 时：'X'-'A' = 23, +3 = 26, 'A'+26 = '['  → 输出 "[\]"
//      正确结果应该是 "ABC"。
//      原因：偏移量超过 25 后没有"绕回"字母表开头，应该对 26 取模。
//      （这类错误叫"边界条件 bug"——你只测了 abc 这种顺利的情况，
//        没有测 XYZ 这种边界情况。这是新手最常见的失分点。）
//
//  【问题 2 · 结构问题】所有逻辑都堆在 main 里
//      加密规则、字符判断、输入输出全混在一起。
//      本示例拆成 shift_one() 和 caesar() 两个函数，每个只做一件事。
//
//  对照阅读：教材第 7 章「函数——C++ 的编程模块」(p219 起)
//            教材 7.1.2 函数原型和函数调用 (p222)
// ============================================================

#include <iostream>
#include <string>

// ------------------------------------------------------------
//  函数原型（prototype）
//  提前告诉编译器："有一个叫 caesar 的函数，接收 string 和 int，返回 string"。
//  这样即使定义写在后面，编译器也能检查你的调用对不对。
//  教材 p222 讲这个。
// ------------------------------------------------------------
std::string caesar(const std::string& text, int step);

// ------------------------------------------------------------
//  shift_one：只做一件事 —— 把"一个字母"偏移 step 位
//  非字母字符原样返回。
//
//  参数用 char 按值传递（值很小，复制代价可忽略）。
// ------------------------------------------------------------
char shift_one(char c, int step)
{
    const int kAlpha = 26;          // 字母表有 26 个字母

    if (c >= 'A' && c <= 'Z')       // 大写字母
    {
        int offset = (c - 'A' + step) % kAlpha;   // ← 取模：这就是修复 bug 的关键
        if (offset < 0) offset += kAlpha;         // C++ 的 % 对负数结果是负的，要修正
        return static_cast<char>('A' + offset);
    }

    if (c >= 'a' && c <= 'z')       // 小写字母
    {
        int offset = (c - 'a' + step) % kAlpha;
        if (offset < 0) offset += kAlpha;
        return static_cast<char>('a' + offset);
    }

    return c;                       // 空格、标点、数字：原样返回
}

// ------------------------------------------------------------
//  caesar：对整个字符串做凯撒加密
//
//  参数用 const std::string&（const 引用）：
//    - 加 & 是为了不复制整个字符串（引用 = 别名，教材第 8 章 p272）
//    - 加 const 是承诺"我不会修改你传进来的字符串"
//  这是 C++ 里传递"只读的大对象"的标准写法，一定要养成习惯。
// ------------------------------------------------------------
std::string caesar(const std::string& text, int step)
{
    std::string result;
    result.reserve(text.size());    // 预先分配空间，避免反复扩容（性能习惯）

    for (std::size_t i = 0; i < text.size(); ++i)
    {
        result += shift_one(text[i], step);
    }
    return result;
}

// ------------------------------------------------------------
//  main：只负责"和用户打交道"
// ------------------------------------------------------------
int main()
{
    std::cout << "请输入要加密的一行文字: ";

    std::string line;
    if (!std::getline(std::cin, line))   // getline 比 cin >> 更适合读整行
    {
        std::cout << "读取输入失败\n";
        return 1;                        // 返回非 0 表示程序异常结束
    }

    const int step = 3;                  // const：这个值之后不该被改动

    std::string cipher = caesar(line, step);

    std::cout << "原文: " << line << '\n';
    std::cout << "密文: " << cipher << '\n';
    std::cout << "解密: " << caesar(cipher, -step) << "   <- 偏移 -3 就还原了\n";

    return 0;
}
