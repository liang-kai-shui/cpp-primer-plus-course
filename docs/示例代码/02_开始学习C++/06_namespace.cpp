// ============================================================
//  示例 6：访问名称空间 std 的四种写法
//              （对应教材 p50-52）
// ------------------------------------------------------------
//  你一直写 using namespace std; —— 它到底做了什么？
//  这个文件把 4 种写法放在一起对比。
// ============================================================

#include <iostream>

// ---------- 写法 ①：放在所有函数之前（杀伤力最大）----------
// using namespace std;
// 效果：从这行往下，**文件里所有函数**都能直接用 cout、endl、string……
// 缺点：整个文件的命名空间被"污染"，大型项目里容易撞名字。

// ---------- 写法 ③：只引入指定的元素（折中，很多人推荐）----------
using std::cout;
using std::endl;
// 效果：只有 cout 和 endl 能省掉 std::，别的（比如 string）还得写 std::

// ============================================================
//  下面两个函数演示另外两种写法
// ============================================================

void style_two()      // 写法 ②：using 放在函数内部
{
    using namespace std;                 // 只在这个函数里生效
    cout << "[写法②] using namespace std; 写在函数内部，只影响本函数" << endl;
}

void style_four()     // 写法 ④：完全不用 using，老老实实写 std::
{
    std::cout << "[写法④] 每次都写前缀 std:: ，最明确、最安全" << std::endl;
}

int main()
{
    // 因为第 18-19 行用了 using std::cout; using std::endl;，
    // 所以 main 里可以省掉 std::
    cout << "[写法③] using std::cout; 只引入需要的名字" << endl;

    style_two();
    style_four();

    // 但如果要用 string，写法 ③ 并没有引入它，所以必须写全：
    std::string msg = "（这行用了 std::string，因为上面没 using std::string）";
    std::cout << msg << std::endl;

    return 0;
}

// ============================================================
//  【总结】教材 p52 的四种写法
//    ① using namespace std;         放在文件顶部   —— 方便，但影响全文件
//    ② using namespace std;         放在函数内部   —— 影响范围最小的小偷懒
//    ③ using std::cout;             放在文件顶部   —— 只引入需要的，推荐
//    ④ 完全不 using，写 std::cout    —— 最明确，头文件里必须这样
//
//  【建议】
//    现在：继续用 ①（`using namespace std;` 写在 main 里），方便学习
//    L13 学多文件工程后：头文件里绝不能用 ①，那时改成 ④
//    等你代码超过 300 行：开始用 ③
//
//  ⚠️ 教材 p52 特别提到："将 using namespace std; 放在函数定义之前"
//     是**最省事但最不推荐**的做法之一（会污染整个文件）。
// ============================================================