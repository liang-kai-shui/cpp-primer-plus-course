// ============================================================
//  示例 5：有返回值的用户定义函数
//              （对应教材 p49-50，程序清单 2.6）
// ------------------------------------------------------------
//  示例 4 的函数是 void（不返回值），这个示例的函数**返回值**。
//  返回值让函数能"算出东西交给别人用"——这才是函数的真正威力。
// ============================================================

#include <iostream>

int stonetolb(int);          // 函数原型：接收 int，返回 int

int main()
{
    using namespace std;

    int stone;
    cout << "Enter the weight in stone: ";
    cin >> stone;

    int pounds = stonetolb(stone);    // ← 函数调用出现在赋值号右边！
                                      //   函数算出结果，赋给 pounds
    cout << stone << " stone = " << pounds << " pounds." << endl;

    return 0;
}

// ------------------------------------------------------------
//  函数定义：有返回值就必须有 return
//  return 干两件事：① 把值交给调用者 ② 立刻结束这个函数
// ------------------------------------------------------------
int stonetolb(int sts)
{
    return 14 * sts;         // 1 stone = 14 pounds
}

// ------------------------------------------------------------
//  【教材 p50 的要点】函数原型里可以省略参数名，只写类型：
//      int stonetolb(int);          ← 合法，推荐（更清楚）
//      int stonetolb(int sts);      ← 也合法
//  但定义里**必须**写参数名，因为你要用它：
//      int stonetolb(int sts) { return 14 * sts; }
//
//  【p44 还讲了】有些函数你不写返回值类型也能用（库函数），
//  但你自己写的函数一定要写，否则编译器会警告甚至报错。
// ------------------------------------------------------------