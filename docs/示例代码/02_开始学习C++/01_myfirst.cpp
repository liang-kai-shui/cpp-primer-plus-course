// ------------------------------------------------------------
//  这个程序故意写得很小，但每一行都值得抠。
//  读完教材 2.1 节（p29-37）再回来看注释。
// ============================================================

#include <iostream>          // ① 预处理指令：把 iostream 的内容原样插进来
                             //    ⚠️ 注意没有分号！它是给预处理器的命令，不是 C++ 语句

int main()                   // ② 函数头：程序从 main 开始执行
{                            // ③ 函数体开始（这个 { 的写法叫 Allman 风格，教材 p36 讨论过）
    using namespace std;     // ④ 让 std 里的名字可以直接用（否则要写 std::cout）

    cout << "Come up and C++ me some time.";   // ⑤ 消息语句：把字符串插进 cout
    cout << endl;                              // ⑥ endl：换行 + 刷新缓冲区

    cout << "You won't regret it!" << endl;    // ⑦ 可以连着写多个 <<
                                               //    注意字符串里的 ' 不需要转义（和 Python 一样）

    return 0;                // ⑧ 返回给操作系统：0 表示"一切正常"
}                            // ⑨ 函数体结束
                             //    main 的 } 后不写分号！这是 common 错误