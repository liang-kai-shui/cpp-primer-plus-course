#include <iostream>

int main()
{
    using namespace std;
    cout << 5 / 2 * 2 << endl;   // 你猜: ___4___   实际: ___4___
    cout << 5 * 2 / 2 << endl;   // 你猜: ___5___   实际: ___5___
    cout << 5 / 2.0 * 2 << endl; // 你猜: ______   实际: ______

    cout << "===== 教材复习题第 8 题，逐条验证 =====\n";
    cout << "a. 8 * 9 + 2   = " << 8 * 9 + 2 << "   (乘法先算)\n";
    cout << "b. 6 * 3 / 4   = " << 6 * 3 / 4 << "   <- 18/4，整数除法截断\n";
    cout << "c. 3 / 4 * 6   = " << 3 / 4 * 6 << "   <- 先算 3/4 = 0，再 0*6\n";
    cout << "d. 6.0 * 3 / 4 = " << 6.0 * 3 / 4 << "   <- 有 double 参与，全程浮点\n";
    cout << "e. 15 % 4      = " << 15 % 4 << "\n";

    cout << "\n【注意 b 和 c 的对比】两个表达式数字完全一样，结果却不同！\n";
    cout << "  b: 6*3/4 -> 先乘后除 -> 18/4 = 4\n";
    cout << "  c: 3/4*6 -> 先除      -> 0*6  = 0\n";
    cout << "  原因：整数除法**从左到右**算，中间结果被截断了。\n";

    cout << "\n===== 整数除法的截断方向 =====\n";
    cout << "7 / 2   = " << 7 / 2 << "   <- 不是 3.5，也不是四舍五入的 4\n";
    cout << "-7 / 2  = " << -7 / 2 << "   <- C++11 起规定：向 0 截断（不是向负无穷）\n";

    cout << "\n===== 求模 % (取余数) =====\n";
    cout << "15 % 4  = " << 15 % 4 << "\n";
    cout << "15 % 5  = " << 15 % 5 << "\n";
    cout << "-15 % 4 = " << -15 % 4 << "   <- 余数的符号跟着**左边**走\n";
    // cout << 15.0 % 4; // ← 取消注释试试：浮点数不能用 %

    cout << "\n【% 的典型用途】判断能否整除、取数字的各位、循环绕圈\n";
    cout << "  31600000 秒里有多少秒是'不足一分钟'的？ 31600000 % 60 = " << 31600000 % 60 << "\n";

    return 0;
}