#include <iostream>

int main()
{
    using namespace std;

    // ---------- 复习题第 5 题：这两条语句等价吗？----------
    char grade1 = 65;           // 用数字初始化
    char grade2 = 'A';          // 用字符初始化
    cout << "char grade1 = 65;  输出: " << grade1 << "\n";
    cout << "char grade2 = 'A'; 输出: " << grade2 << "\n";
    cout << "把它们的数值打出来: " << (int)grade1 << " 和 " << (int)grade2 << "\n";
    cout << "-> 等价！因为 'A' 的 ASCII 编码就是 65\n";

    cout << "\n===== 复习题第 6 题：怎么找出编码 88 表示的字符？=====\n";
    cout << "方法一（用 char 变量）: " << (char)88 << "\n";
    cout << "方法二（打印时用强制转换）: " << static_cast<char>(88) << "\n";

    cout << "\n===== 为什么 I/O 系统知道该当字符还是数字？=====\n";
    char c = 'A';
    cout << "cout << c       -> " << c << "        (当字符)\n";
    cout << "cout << (int)c  -> " << (int)c << "       (当数字)\n";
    cout << "同 8 个 bit，解释方式不同，显示就不同。\n";

    cout << "\n===== 转义字符（教材 p66）=====\n";
    cout << "换行\\n 用数值表示是 10，试试: [" << (char)10 << "]" << "（看到换行了吗）\n";
    cout << "制表符\\t: [\t]\n";
    cout << "单引号\\': [']\n";

    return 0;
}