//  L04 · 示例 4：C 风格字符串的本质      ★★ 本课最重要的概念 ★★
//              （教材 4.2, p91-94）
// ------------------------------------------------------------
//  【一句话】C 风格字符串 = 以 '\0' 结尾的 char 数组。
//
//  【为什么需要 '\0'？】
//    数组自己【不知道】自己有多长！int a[10] 就是 10 个 int，
//    但 char s[100] 里真正用了多少个字符？数组不知道。
//    所以约定：在有效字符后面放一个特殊字符 '\0'（数值 0），
//    读到它就知道「字符串到此结束」。
// ============================================================
#include <iostream>
#include <cstring>              // strlen 等字符串函数在这里

int main()
{
    using namespace std;

    // ---------- 字符数组 != 字符串 ----------
    char dog[8] = {'b', 'e', 'a', 'u', 'x', ' ', 'I', 'I'};   // 没有 '\0'
    char cat[8] = {'f', 'a', 't', 'e', 's', 's', 'a', '\0'};  // 有 '\0' -> 是字符串

    cout << "char dog[8] = {'b','e','a','u','x',' ','I','I'};  (无 \\0)\n";
    cout << "  当成字符串输出 -> ";
    cout << dog;                     // 危险！它会一直往后读，直到碰到 '\0' 才停
    cout << "   <- 看起来很正常，但这是【运气】\n";
    cout << "      dog 里根本没有结束标记 —— 它能停下来，只是因为\n";
    cout << "      紧跟其后的那块内存【恰好】是 0。换个编译器、换个位置，就未必。\n";
    cout << "      ★ 判断「它是不是字符串」的标准，是【数组里有没有 '\\0'】，\n";
    cout << "        而不是「这次打印出来正不正常」★\n";

    cout << "\nchar cat[8] = {...'a','\\0'};  (有 \\0)\n";
    cout << "  当成字符串输出 -> " << cat << "   <- 正常\n";

    // ---------- 用字符串字面量初始化：自动加 '\0' ----------
    char fish[] = "bubbles";         // 7 个字母 + 1 个 '\0' = 8 字节
    cout << "\nchar fish[] = \"bubbles\";\n";
    cout << "  sizeof(fish) = " << sizeof(fish) << "  <- 8（含结尾的 \\0）\n";
    cout << "  strlen(fish) = " << strlen(fish) << "  <- 7（不含 \\0）\n";
    cout << "  ★ 这两个数差 1，是考试最爱考的 ★\n";

    // ---------- 陷阱：数组太小放不下 '\0' ----------
    cout << "\n【陷阱】\n";
    cout << "  char bad[4] = \"abcd\";   // \"abcd\" 需要 5 个字节（含 \\0）\n";
    cout << "  C++11 起会直接报错：initializer-string for array of chars is too long\n";

    // ---------- 逐个字符看 '\0' 在哪 ----------
    cout << "\n把 fish 的每个字节的数值打出来：\n  ";
    for (unsigned i = 0; i < sizeof(fish); ++i)
    {
        cout << (int)fish[i] << " ";
    }
    cout << "\n  ^ 最后那个 0 就是 '\\0'（字符串结束标记）\n";

    return 0;
}