// ============================================================
//  L04 · 示例 3：数组【没有】边界检查         ★ 危险，必看 ★
//              （教材 4.1, p89 提到；第 1 章「错误分类实验」的 E 是同一个现象）
// ------------------------------------------------------------
//  这是 C++ 最著名的「坑」，也是它快的原因之一：
//  squares[i] 只是「起始地址 + i 个元素」，它【不检查】i 是否越界。
// ============================================================
#include <iostream>

int main()
{
    using namespace std;

    // ---------- 危险 1：读越界 ----------
    int squares[5] = {1, 4, 9, 16, 25};
    cout << "合法范围：squares[0] ~ squares[4]\n";
    cout << "squares[4]   = " << squares[4]   << "   (合法，最后一个)\n";
    cout << "squares[5]   = " << squares[5]   << "   <- 越界读（这次读出来是 0）\n";
    cout << "squares[100] = " << squares[100] << "   <- 越界 100 个（这次也是 0）\n";
    cout << "  ^ 不报错、不崩溃，只是给你一块【不属于你的内存】的内容\n";
    cout << "\n  ⚠️ 请特别注意：这次两个越界读【读出来都是 0】。\n";
    cout << "     这正是越界最坑的地方 —— 0 看起来「很正常」，\n";
    cout << "     于是很容易得出「越界也没事」的错误结论。\n";
    cout << "     但 0 同样是垃圾值：它只说明「这块内存里恰好是 0」，\n";
    cout << "     不代表「这个位置就是 0」。\n";
    cout << "     换台机器、改个编译选项、甚至只是重启一次，\n";
    cout << "     它就可能变成任意数字，也可能直接崩溃。\n";

    // ---------- 危险 2：写越界（更可怕）----------
    cout << "\n写越界会【破坏别的变量的数据】：\n";
    int victim = 12345;                 // 一个无辜的变量
    int small[3] = {1, 2, 3};
    cout << "  small 有 " << sizeof(small) / sizeof(small[0]) << " 个元素，victim = " << victim << "\n";
    // small[5] = 999;                  // <- 取消注释试试（后果随机）
    // cout << "  改动 victim = " << victim << "  <- 可能被覆盖了！\n";
    cout << "  （上面那行我故意注释掉了，因为后果不可预测 —— 这正是它可怕的地方）\n";

    cout << "\n【结论】\n";
    cout << "  1. C++ 默认不检查数组越界（第 1 章「错误分类实验」的 E 就是这个）\n";
    cout << "  2. 后果叫「未定义行为」：可能没事、可能出错误结果、可能崩溃\n";
    cout << "  3. 防身三招：\n";
    cout << "       1) 老老实实写 i < n，别写 <=\n";
    cout << "       2) 用 std::vector 的 .at()（越界会抛异常）\n";
    cout << "       3) 打开 -fsanitize=address 让工具帮你抓（后面教）\n";

    return 0;
}