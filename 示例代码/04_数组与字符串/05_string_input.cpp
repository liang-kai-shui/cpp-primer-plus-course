// ============================================================
//  L04 · 示例 5：三种字符串输入方式的区别 （教材 4.2.3-4.2.4, p94-98）
// ------------------------------------------------------------
//    cin >> s            遇空白符停，且【不能限制长度】（危险）
//    cin.getline(s, n)   读一整行，【丢掉】换行符
//    cin.get(s, n)       读一整行，【保留】换行符 <- 差别就在这
// ============================================================
#include <iostream>

int main()
{
    using namespace std;

    // ---------- 方式一：cin >> ----------
    char name1[20];
    cout << "【方式一 cin >>】请输入你的全名: ";
    cin >> name1;
    cout << "  读到的是: \"" << name1 << "\"\n";
    cout << "  注意：只读到第一个空格就停了，而且输入超过 19 个字符会溢出！\n\n";

    // ---------- 方式二：cin.getline ----------
    cin.get();                          // <- 先吃掉上一次输入留下的换行符
    char name2[20];
    cout << "【方式二 cin.getline】请输入你的全名: ";
    cin.getline(name2, 20);             // 最多读 19 个字符 + '\0'
    cout << "  读到的是: \"" << name2 << "\"\n";
    cout << "  好：空格也读进来了，而且长度受保护（最多 19 个字符）\n\n";

    // ---------- 方式三：cin.get ----------
    char name3[20];
    char next[20];
    cout << "【方式三 cin.get】请输入你的全名: ";
    cin.get(name3, 20);                 // 注意：换行符【还留在】输入队列里！
    cout << "  第一次读: \"" << name3 << "\"\n";

    cin.get(next, 20);                  // 于是第二次读到的是个空行！
    cout << "  紧接着再读一次: \"" << next << "\"  <- 空的！因为换行符还在队列里\n";
    cout << "  -> 这就是 getline 和 get 的核心区别。\n";
    cout << "  -> 用 get 的时候，读完要自己再 cin.get() 一次把换行符吃掉。\n";

    cout << "\n【怎么选】\n";
    cout << "  读整行  ->  cin.getline(s, n)    最省心，首选\n";
    cout << "  需要知道为什么停（读满了？还是遇到换行？）-> 用 cin.get(s, n)\n";
    cout << "  只读一个单词 -> cin >> s\n";

    return 0;
}