#include <iostream>

int main()
{
    using namespace std;

    // ---------- 规则 1：不初始化 → 全是垃圾值 ----------
    // 注意：下面这一行会触发一个警告，这是【故意】留给你看的：
    //   warning: 'a1[0]' may be used uninitialized in this function
    // 它证明：开了 -Wall，编译器会主动提醒你「这个变量没初始化就用」。
    int a1[3];
    cout << "int a1[3];                -> " << a1[0] << " " << a1[1] << " " << a1[2]
         << "   <- 垃圾值（每次运行可能不同）\n";

    // ---------- 规则 2：部分初始化 → 剩下的自动补 0 ★重要★ ----------
    int a2[5] = {1, 2};
    cout << "int a2[5] = {1, 2};       -> ";
    for (int i = 0; i < 5; ++i) cout << a2[i] << " ";
    cout << "  <- 后面三个自动变 0！\n";

    // ---------- 规则 3：{0} 是「全部清零」的常用技巧 ----------
    int a3[5] = {0};
    cout << "int a3[5] = {0};          -> ";
    for (int i = 0; i < 5; ++i) cout << a3[i] << " ";
    cout << "  <- 全部是 0\n";

    // ---------- 规则 4：省略大小 → 编译器自己数 ----------
    int a4[] = {10, 20, 30, 40};
    cout << "int a4[] = {10,20,30,40}; -> 编译器数出 " << sizeof(a4) / sizeof(a4[0]) << " 个元素\n";

    // ---------- 规则 5（C++11）：可以省略等号 ----------
    int a5[3]{7, 8, 9};
    int a6[3]{};                       // 全部 0（C++11 新写法）
    cout << "int a5[3]{7, 8, 9};       -> " << a5[0] << " " << a5[1] << " " << a5[2] << "\n";
    cout << "int a6[3]{};              -> " << a6[0] << " " << a6[1] << " " << a6[2] << "  (全 0)\n";

    // ---------- 规则 6：大小必须是编译期常量 ----------
    const int kSize = 4;
    int good[kSize] = {1, 2, 3, 4};       // 合法：kSize 是编译期常量
    cout << "\nconst int kSize = 4; int good[kSize] = {1,2,3,4};\n";
    cout << "  good 的内容：";
    for (int i = 0; i < kSize; ++i) cout << good[i] << " ";
    cout << "  <- 合法，因为 kSize 是编译期常量\n";
    cout << "  但 int n; cin >> n; int bad[n];  -> 非法（变长数组不是标准 C++）\n";

    return 0;
}