// ============================================================
//  示例 4：用户定义函数 + 函数原型 ★ 核心概念 ★
//              （对应教材 p46-48，程序清单 2.5）
// ------------------------------------------------------------
//  这个程序只有 30 行，但它包含了你从"会做题"走向"会写程序"
//  所需要的最重要的一个知识点：**函数原型**。
//
//  对比一下：
//    没有函数时：所有代码堆在 main 里，60 行、100 行、200 行……
//    有了函数后：main 只负责"流程"，细节交给专门的函数
// ============================================================

#include <iostream>

void simon(int);             // ★ 函数原型（prototype）★
                             //   告诉编译器："有一个叫 simon 的函数，
                             //   接收一个 int，不返回值（void）。"
                             //   注意：这行必须有分号；函数定义的 } 后不加分号

int main()
{
    using namespace std;

    simon(3);                // 调用 simon，把 3 传进去

    cout << "Pick an integer: ";
    int count;
    cin >> count;

    simon(count);            // 同一个函数，换个参数再调用一次

    cout << "Done!" << endl;
    return 0;
}

// ------------------------------------------------------------
//  函数定义（definition）：这里才是函数"真正做什么"
//  函数头 void simon(int n) 必须和上面的原型一致（void + 一个 int）
// ------------------------------------------------------------
void simon(int n)
{
    using namespace std;     // 只在 simon 里生效（教材 2.4.5 讲这个选择）
    cout << "Simon says touch your toes " << n << " times." << endl;
}

// ------------------------------------------------------------
//  【最重要的认知】
//
//  为什么必须有函数原型？
//  C++ 是"从上往下"读代码的。编译器读到 main 里的 simon(3) 时，
//  它还不知道 simon 是什么。原型就是提前给它一张"说明书"。
//
//  如果你删掉第 15 行的原型会怎样？
//  -> 报错：'simon' was not declared in this scope（编译错误）
//  -> 把 simon 的定义整个挪到 main 前面，也能通过（但函数一多就乱了）
//
//  这就是"声明（declaration）"和"定义（definition）"的区别：
//    声明 = 说明书（长什么样）    -> 可以有多个
//    定义 = 实物（做什么）        -> 只能有一个
//  这个区别，第 1 章讲链接错误时就出现过一次。
// ------------------------------------------------------------