// ============================================================
//  L05 · 示例 2：结构【可以】整体赋值 —— 和数组对比
//              （教材 4.4.4 其他结构属性, p108-110）
// ------------------------------------------------------------
//  L04 讲过：数组不能整体赋值（b = a; 是编译错误）。
//  结构【可以】。这是它比数组好用的地方之一。
// ============================================================
#include <iostream>
#include <string>

struct Point
{
    int x;
    int y;
};

int main()
{
    using namespace std;

    Point p1 = {3, 4};
    Point p2;

    p2 = p1;                          // 结构可以整体赋值：逐成员复制一份
    cout << "p1 = (" << p1.x << ", " << p1.y << ")\n";
    cout << "p2 = (" << p2.x << ", " << p2.y << ")   <- 从 p1 复制来的\n";

    p2.x = 100;                       // 改 p2 不影响 p1（是复制，不是共享）
    cout << "\n把 p2.x 改成 100 之后：\n";
    cout << "  p1.x = " << p1.x << "   <- 没变\n";
    cout << "  p2.x = " << p2.x << "\n";
    cout << "  ^ 是「各有一份」，不是「指向同一份」\n";

    // ---------- 对比：数组就不行 ----------
    int a[3] = {1, 2, 3};
    int b[3] = {9, 9, 9};
    // b = a;                         // <- 取消注释试试：编译错误
    cout << "\n【对比】数组内容 a[0]=" << a[0] << "，b[0]=" << b[0] << "\n";
    cout << "  int b[3]; b = a;      -> 编译错误（L04 讲过）\n";
    cout << "  Point p2; p2 = p1;    -> 合法（结构可以）\n";

    // ---------- 结构数组的元素也可以整体赋值 ----------
    Point list[3] = {{1, 1}, {2, 2}, {3, 3}};
    Point first = list[0];            // 元素是结构，所以可以
    cout << "\n结构数组的元素也能整体赋值：first = (" << first.x << ", " << first.y << ")\n";

    // ---------- 结构可以做函数参数和返回值（这里先看一眼，第 7 章细讲）----------
    cout << "\n【预告】结构还能当函数参数、当返回值 —— 这在第 7 章会大量用到。\n";

    return 0;
}
