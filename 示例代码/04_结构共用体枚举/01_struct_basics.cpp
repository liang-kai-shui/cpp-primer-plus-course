// ============================================================
//  L05 · 示例 1：结构是什么，怎么用          （教材 4.4, p105-108）
// ------------------------------------------------------------
//  【先想一个问题】要描述一个学生，需要哪些信息？
//     姓名（字符串）、年龄（整数）、成绩（小数）—— 三种不同类型。
//
//  L04 的数组解决的是「一堆【同类型】数据」，但它装不下这种。
//  结构就是补上这一块的：
//     把【不同类型】的数据打包成一个整体，起一个名字。
// ============================================================
#include <iostream>
#include <string>

// ---------- 第一步：声明一个「结构模板」（描述这种数据长什么样）----------
// ⚠️ 这一步【不分配任何内存】，只是告诉编译器：有这么一种新类型。
struct Student
{
    std::string name;      // 成员 1
    int         age;       // 成员 2
    double      score;     // 成员 3
};                         // ← 这个分号不能少！新手最常忘

int main()
{
    using namespace std;

    // ---------- 第二步：用这个类型定义变量（现在才真正分配内存）----------
    Student s1;

    // ---------- 第三步：用「点」访问各个成员 ----------
    s1.name  = "Li Ming";
    s1.age   = 19;
    s1.score = 92.5;

    cout << "姓名: " << s1.name  << "\n";
    cout << "年龄: " << s1.age   << "\n";
    cout << "成绩: " << s1.score << "\n";

    // ---------- 声明的同时初始化：大括号里的顺序必须和声明一致 ----------
    Student s2 = {"Wang Fang", 20, 88.0};
    cout << "\ns2 = " << s2.name << ", " << s2.age << ", " << s2.score << "\n";

    // ---------- C++11：可以省略等号（和数组一样）----------
    Student s3{"Zhang Wei", 18, 95.5};
    cout << "s3 = " << s3.name << ", " << s3.age << ", " << s3.score << "\n";

    // ---------- 成员就是普通变量，可以参与运算 ----------
    double avg = (s1.score + s2.score + s3.score) / 3;
    cout << "\n三人平均分: " << avg << "\n";

    // ---------- sizeof：整个结构占多少字节 ----------
    cout << "\nsizeof(Student) = " << sizeof(Student) << " 字节\n";
    cout << "  注意：它【不一定】等于各成员大小之和。\n";
    cout << "  编译器为了让成员落在对齐的地址上，会在中间插入空隙（叫「内存对齐」）。\n";
    cout << "  教材 p109 讲过这件事，知道有这回事即可。\n";

    return 0;
}
